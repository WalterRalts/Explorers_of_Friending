Dreset = {}

function Dreset.Guild()
      COMMON.RespawnAllies()
      local maru = CH("PLAYER")
      local azura = CH("Teammate1")
      local rexio = CH("Teammate2")
      local embu = CH("Emburst")
      GAME:WaitFrames(45)
      UI:SetSpeaker(embu)
      UI:SetSpeakerEmotion("Worried")
      UI:WaitShowDialogue("...I guess children technically can't be sheriffed away anyway.")
      UI:SetSpeakerEmotion("Normal")

      local function question()
            EXPLCOMMON.CharQuestion("Emburst")
      end
      UI:WaitShowDialogue("You're looking for,[pause=40] who was it,[pause=25][script=0] Kitkat?", {question})

      UI:SetSpeaker(rexio)
      UI:SetSpeakerEmotion("Normal")
      UI:WaitShowDialogue("You know her?")

      local function up()
            GROUND:CharAnimateTurnTo(embu, Dir8.Up, 5)
      end

      UI:SetSpeaker(embu)
      UI:SetSpeakerEmotion("Normal")
      UI:WaitShowDialogue("Nah, guild master does, she's outside.[script=0] Just go straight ahead.", {up})
      local coro1 = TASK:BranchCoroutine(function()
            UI:SetSpeakerEmotion("Normal")
            UI:WaitShowDialogue("Not many of us here today,[pause=40] so I don't think you're allowed to go anywhere else.")
            UI:WaitShowDialogue("Go ask her about it and leave, will ya?")
      end)
      local coro2 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(40)
            GROUND:MoveToMarker(embu, MRKR("Flared"), false, 1)
            GROUND:CharAnimateTurnTo(embu, Dir8.DownLeft, 5)
      end)
      TASK:JoinCoroutines({coro1, coro2})
      SV.Story.sect = 3
      EXPLCOMMON.AllyFollow(false, false)
end

function Dreset.Exiting()
      COMMON.RespawnAllies()
      local maru = CH("PLAYER")
      local azura = CH("Teammate1")
      local rexio = CH("Teammate2")
      local embu = CH("Emburst")
      local hertz = CH("Hertz Guildmaster")
      GROUND:Unhide("Hertz Guildmaster")
      GAME:MoveCamera(0, 0, 1, true)
      EXPLCOMMON.TeleportToMarker(embu, "Flared", Dir8.DownLeft)
      EXPLCOMMON.TeleportToMarker(azura, "a1", Dir8.Down)
      EXPLCOMMON.TeleportToMarker(rexio, "r1", Dir8.Down)

      --Speedy Rexio
      local function rnotice()
            GROUND:CharTurnToChar(rexio, embu)
      end
      local coro1 = TASK:BranchCoroutine(function()
            local c3 = TASK:BranchCoroutine(function()
                  GROUND:AnimateToPosition(azura, "Walk", Dir8.Down, azura.Position.X, MRKR("r2").Position.Y + 50, 1, 1, 0)
                  end)
            local c4 = TASK:BranchCoroutine(function()
                  GROUND:MoveToMarker(rexio, MRKR("r2"), true, 6)
                  GROUND:CharAnimateTurnTo(embu, Dir8.Left, 5)
                  end)
            local c5 = TASK:BranchCoroutine(function()
                  GROUND:AnimateToPosition(maru, "Walk", Dir8.Down, maru.Position.X, MRKR("r2").Position.Y + 50, 1, 1, 0)
                  end)
            local c2 = TASK:BranchCoroutine(function()
                  GAME:WaitFrames(25)
                  GROUND:AnimateToPosition(hertz, "Walk", Dir8.Down, maru.Position.X, MRKR("r2").Position.Y + 100, 1, 1, 0)
                  end)
            local c6 = TASK:BranchCoroutine(function()
                  GAME:FadeIn(90)
                  end)
            TASK:JoinCoroutines({c2, c3, c4, c5, c6})
      end)
      local coro2 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(100)
            UI:SetSpeaker(embu)
            UI:SetSpeakerEmotion("Worried")
            UI:WaitShowDialogue("I'm assuming this means you're done, then.[script=0]", {rnotice})
            EXPLCOMMON.CharQuestion("Emburst")
            GROUND:MoveToMarker(embu, MRKR("Flared"), false, 1)
      end)
      TASK:JoinCoroutines({coro1, coro2})

      UI:SetSpeaker(rexio)
      UI:SetSpeakerEmotion("Happy")
      EXPLCOMMON.CharHop("Teammate2")
      UI:WaitShowDialogue("Treasure!")

      UI:SetSpeaker(embu)
      UI:SetSpeakerEmotion("Normal")
      UI:WaitShowDialogue("Good for you.")

      local coro3 = TASK:BranchCoroutine(function()
            local c1 = TASK:BranchCoroutine(function()
                  GROUND:AnimateToPosition(maru, "Walk", Dir8.Down, maru.Position.X, rexio.Position.Y - 35, 0.5, 0.2, 0)
            end)
            local c2 = TASK:BranchCoroutine(function()
                  local a1 = TASK:BranchCoroutine(function()
                        GAME:WaitFrames(20)
                        GROUND:AnimateToPosition(azura, "Walk", Dir8.Down, rexio.Position.X - (maru.Position.X - rexio.Position.X), rexio.Position.Y - 35, 1, 1, 0)
                  end)
                  local a2 = TASK:BranchCoroutine(function()
                        GAME:WaitFrames(30)
                        UI:SetSpeaker(maru)
                        UI:SetSpeakerEmotion("Normal")
                        UI:WaitShowDialogue("So where would the treasure be?")

                        UI:SetSpeaker(rexio)
                        UI:SetSpeakerEmotion("Normal")
                        UI:WaitShowDialogue("Good question, easy answer, let's go, town time, hurry up.")
                        GROUND:CharAnimateTurnTo(rexio, Direction.Down, 4)
                  end)
                  TASK:JoinCoroutines({a1, a2})
            end)
            TASK:JoinCoroutines({c1, c2})
      end)
      local coro4 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(hertz, "Walk", Dir8.Down, embu.Position.X - 36, embu.Position.Y, 1, 1, 0)
      end)
      TASK:JoinCoroutines({coro3, coro4})
      EXPLCOMMON.AllyFollow(false, false)
end