Seed = {}

function Seed.AppleOut()
    COMMON.RespawnAllies()
    GAME:CutsceneMode(true)
    GAME:MoveCamera(168, 120, 0, false)
    local maru = CH("PLAYER")
    local azura = CH("Teammate1")
    local rexio = CH("Teammate2")
    local gold = OBJ("GoldApple")
    maru.CollisionDisabled = true
    azura.CollisionDisabled = true
    rexio.CollisionDisabled = true
    UI:SetBounds(10, 16, 300, 50)

    local the1 = TASK:BranchCoroutine(function()
        local wh2 = TASK:BranchCoroutine(function()
            GROUND:MoveToPosition(rexio, gold.Position.X, gold.Position.Y + 50, false, 4)
            EXPLCOMMON.CharRealize("Teammate2")
            GAME:WaitFrames(30)

            EXPLCOMMON.SetCharAndEmotion(rexio, "Inspired")
            UI:WaitShowDialogue("Whoa! Goooold!")
            GROUND:MoveToPosition(rexio, gold.Position.X, gold.Position.Y + 30, false, 4)
            EXPLCOMMON.CharHappyHop("Teammate2")
            end)
        local wh3 = TASK:BranchCoroutine(function()
            GAME:FadeIn(60)
            end)
        TASK:JoinCoroutines({wh2, wh3})
        end)
    local the2 = TASK:BranchCoroutine(function()
        GAME:WaitFrames(35)
        GROUND:MoveToPosition(azura, rexio.Position.X + 12, 188, false, .25)
        end)
    local the3 = TASK:BranchCoroutine(function()
        GAME:WaitFrames(25)
        GROUND:MoveToPosition(maru, rexio.Position.X - 12, rexio.Position.Y + 30, false, 1)
        end)
    TASK:JoinCoroutines({the1, the2, the3})

    local c1 = TASK:BranchCoroutine(function()
        EXPLCOMMON.StartTremble(azura)
        GAME:WaitFrames(90)
        EXPLCOMMON.StopTremble(azura)
        GAME:WaitFrames(5)
        GROUND:CharSetAnim(azura, "Sleep", true)
        end)
    local c2 = TASK:BranchCoroutine(function()
        GAME:WaitFrames(30)
        GROUND:MoveToPosition(maru, rexio.Position.X - 12, rexio.Position.Y + 20, false, 0.5)
        end)
    local c3 = TASK:BranchCoroutine(function()
        EXPLCOMMON.SetCharAndEmotion(maru, "Normal")
        UI:WaitShowDialogue("Well, that's neat.")

        GROUND:CharAnimateTurnTo(rexio, Dir8.Down, 3)
        EXPLCOMMON.SetCharAndEmotion(rexio, "Happy")
        EXPLCOMMON.FaceEachother(rexio, maru)
        UI:WaitShowDialogue("Knew we could do it.[pause=20] You worry too much, Bluetail")
        end)
    TASK:JoinCoroutines({c1, c2, c3})

    local function maru_concern()
        GROUND:CharTurnToCharAnimated(maru, azura, 3)
        EXPLCOMMON.CharSweatdrop("PLAYER")
    end
    EXPLCOMMON.SetCharAndEmotion(maru, "Happy")
    UI:WaitShowDialogue("I'm sure the guildmaster would love to see a gold apple[pause=40],[emote=Worried][script=0] but uh...", {maru_concern})

    GROUND:CharTurnToChar(rexio, azura)
    GAME:WaitFrames(80)
    GROUND:MoveToPosition(rexio, azura.Position.X, azura.Position.Y - 16, true, 1)

    GAME:WaitFrames(20)
    EXPLCOMMON.SetCharAndEmotion(rexio, "Worried")
    UI:WaitShowDialogue("...mm...")

    local ah2 = TASK:BranchCoroutine(function()
        GAME:WaitFrames(10)
        GROUND:CharSetAnim(rexio, "Attack", false)
        GAME:WaitFrames(40)
        end)
    local ah3 = TASK:BranchCoroutine(function()
        GAME:WaitFrames(20)
        GROUND:AnimateToPosition(azura, "Sleep", azura.Direction, rexio.Position.X, rexio.Position.Y, 0.5, 2, 6)
        GROUND:CharSetAnim(azura, "Sleep", true)
        end)
    TASK:JoinCoroutines({ah2, ah3})

    GAME:WaitFrames(20)
    EXPLCOMMON.SetCharAndEmotion(maru, "Normal")
    UI:WaitShowDialogue("...I guess that works.")

    local ch2 = TASK:BranchCoroutine(function()
        local bh2 = TASK:BranchCoroutine(function()
            GROUND:MoveToPosition(rexio, azura.Position.X, rexio.Position.Y + 80, false, 0.5)
            end)
        local bh3 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(azura, "Sleep", azura.Direction, rexio.Position.X, rexio.Position.Y + 80, 0.5, 0.5, 6)
            end)
        TASK:JoinCoroutines({bh2, bh3})
        end)
    local ch3 = TASK:BranchCoroutine(function()
        GAME:WaitFrames(20)
        GROUND:MoveToPosition(maru, maru.Position.X, maru.Position.Y + 80, false, 0.5)
        end)
    local ch1 = TASK:BranchCoroutine(function()
        GAME:WaitFrames(10)
        GAME:FadeOut(false, 60)
        end)
    TASK:JoinCoroutines({ch2, ch3, ch1})

    GAME:GivePlayerItem("food_apple_golden")
    GAME:CutsceneMode(false)
    GAME:EnterGroundMap("guild_field", "GuildFieldMain", "Start2")
end