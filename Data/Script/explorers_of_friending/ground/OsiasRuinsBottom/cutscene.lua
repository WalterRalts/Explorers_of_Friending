Bottom = {}

function Bottom.Key()
      GAME:CutsceneMode(true)
      COMMON.RespawnAllies()
      local azura = CH("Teammate1")
      local rexio = CH("Teammate2")
      local maru = CH("PLAYER")
      local hertz = CH("HertzMaster")
      azura.CollisionDisabled = true
      rexio.CollisionDisabled = true
      maru.CollisionDisabled = true
      hertz.CollisionDisabled = true

      --Maru and gang make it here
      EXPLCOMMON.SetUpper()
      local coro3 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(azura, "Walk", Dir8.Up, azura.Position.X, azura.Position.Y - 15, 0.5, 0.2, 0)
            end)
      local coro4 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(rexio, "Walk", Dir8.Up, rexio.Position.X, rexio.Position.Y - 20, 0.4, 0.2, 0)
            end)
      local coro5 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(maru, "Walk", Dir8.Up, maru.Position.X, maru.Position.Y - 15, 0.4, 0.2, 0)
            EXPLCOMMON.SetCharAndEmotion(maru, "Normal")
            UI:WaitShowDialogue("Looks like we made it.")

            EXPLCOMMON.SetCharAndEmotion(azura, "Happy")
            UI:WaitShowDialogue("Yay, yippee, yay!")
            end)
      local coro2 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(25)
            GROUND:AnimateToPosition(hertz, "Walk", Dir8.Up, hertz.Position.X, hertz.Position.Y - 15, 0.4, 0.2, 0)
            end)
      local coro6 = TASK:BranchCoroutine(function()
            GAME:FadeIn(90)
            end)
      TASK:JoinCoroutines({coro2, coro3, coro4, coro5, coro6})

      GROUND:MoveToPosition(hertz, math.floor((maru.Position.X + rexio.Position.X + azura.Position.X) / 3), math.floor((maru.Position.Y + rexio.Position.Y + azura.Position.Y) / 3) - 40, true, 4)
      EXPLCOMMON.SetCharAndEmotion(hertz, "Happy")
      GROUND:CharAnimateTurnTo(hertz, Direction.Down, 3)
      local function charger()
            SOUND:PlaySE("Battle/DUN_Charge_Start")
            GAME:WaitFrames(15)
            SOUND:PlaySE("Battle/DUN_Charge")
            GROUND:CharWaitAnim(hertz, "Charge")
            SOUND:PlaySE("Battle/DUN_Discharge_2")
            GROUND:CharWaitAnim(hertz, "Shock")
            GROUND:CharSetAnim(hertz, "Idle", false)
      end
      UI:WaitShowDialogue("Simple enough with the [script=0]Hertz Guildmaster!", {charger})

      EXPLCOMMON.SetCharAndEmotion(rexio, "Worried")
      UI:WaitShowDialogue("Yeah[pause=10], yeah[pause=10], whatever,[pause=30][emote=Happy] key time, where is it?")

      GROUND:CharAnimateTurnTo(rexio, GAME:RandomDirection(), 3)
      GAME:WaitFrames(15)
      GROUND:CharAnimateTurnTo(rexio, GAME:RandomDirection(), 3)
      GAME:WaitFrames(15)

      --Rexio gets key
      GROUND:CharAnimateTurnTo(rexio, Direction.UpLeft, 3)
      EXPLCOMMON.SetCharAndEmotion(rexio, "Inspired")
      UI:WaitShowDialogue("There!")

      local coro3 = TASK:BranchCoroutine(function()
            GROUND:MoveToPosition(rexio, OBJ("Key").X, OBJ("Key").Y + 30, true, 5)

            local c3 = TASK:BranchCoroutine(function()
                  GAME:WaitFrames(10)
                  GROUND:MoveToMarker(maru, MRKR("m1"), false, 2)
                  GROUND:CharTurnToCharAnimated(maru, rexio, 4)
                  end)
            local c4 = TASK:BranchCoroutine(function()
                  GROUND:CharAnimateTurnTo(rexio, Direction.Up, 3)
                  EXPLCOMMON.SetCharAndEmotion(rexio, "Joyous")
                  GAME:WaitFrames(30)
                  local function tomar()
                        GROUND:CharTurnToCharAnimated(rexio, maru, 4)
                  end
                  UI:WaitShowDialogue("Easy mission![pause=30] [script=0]Let's go get that treasure guys!", {tomar})
                  end)
            local c5 = TASK:BranchCoroutine(function()
                  GAME:WaitFrames(10)
                  GROUND:MoveToMarker(azura, MRKR("a1"), false, 2)
                  GROUND:CharTurnToCharAnimated(azura, rexio, 4)
                  end)
            local c6 = TASK:BranchCoroutine(function()
                  GAME:WaitFrames(25)
                  GROUND:MoveToMarker(hertz, MRKR("h1"), false, 2)
                  GROUND:CharTurnToCharAnimated(hertz, rexio, 4)
                  end)
            TASK:JoinCoroutines({c3, c4, c5, c6})
            end)
      local coro4 = TASK:BranchCoroutine(function()
            GAME:MoveCamera(OBJ("Key").X, OBJ("Key").Y, 200, false)
            GROUND:Hide("Key")
            end)
      TASK:JoinCoroutines({coro3, coro4})

      EXPLCOMMON.SetCharAndEmotion(azura, "Joyous")
      UI:WaitShowDialogue("Yay, treasure time!")

      EXPLCOMMON.SetCharAndEmotion(maru, "Stunned")
      UI:WaitShowDialogue("But where is the treasure...?")

      GROUND:CharAnimateTurnTo(rexio, Dir8.Down, 4)
      EXPLCOMMON.SetCharAndEmotion(rexio, "Normal")
      UI:WaitShowTimedDialogue("Um... uh,[pause=60] more searching, I guess.", 60)

      --They leave
      local cor1 = TASK:BranchCoroutine(function()
            GROUND:MoveInDirection(rexio, Direction.Down, 200, false, 4)
            end)
      local cor2 = TASK:BranchCoroutine(function()
            GROUND:CharAnimateTurnTo(maru, Dir8.Down, 4)
            EXPLCOMMON.SetCharAndEmotion(maru, "Normal")
            UI:WaitShowTimedDialogue("...makes sense.", 90)
            GROUND:MoveInDirection(maru, Direction.Down, 200, false, 2)
            end)
      local cor3 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(30)
            local o1 = TASK:BranchCoroutine(function()
                  GAME:WaitFrames(70)
                  GROUND:MoveInDirection(azura, Direction.Down, 200, false, 3)
            end)
            local o2 = TASK:BranchCoroutine(function()
                  GAME:WaitFrames(25)
                  GROUND:MoveInDirection(hertz, Direction.Down, 200, false, 1)
                  end)
            TASK:JoinCoroutines({o1, o2})
            end)
      local cor4 = TASK:BranchCoroutine(function()
            local v1 = TASK:BranchCoroutine(function()
                  GAME:MoveCamera(OBJ("Key").X, OBJ("Key").Y + 100, 200, false)
            end)
            local w1 = TASK:BranchCoroutine(function()
                  GAME:FadeOut(true, 200)
            end)
            TASK:JoinCoroutines({v1, w1})
            end)
      TASK:JoinCoroutines({cor1, cor2, cor3, cor4})

      --Sneaky sneaky Cacturne...
      GROUND:Hide("PLAYER")
      GROUND:Hide("Teammate1")
      GROUND:Hide("Teammate2")
      GROUND:Hide("HertzMaster")
      local cac1 = CH("cac1")
      local kassy = CH("Kassy")
      local a1 = TASK:BranchCoroutine(function()
            GROUND:Unhide("cac1")
            EXPLCOMMON.SetCharAndEmotion(cac1, "Normal")
            UI:WaitShowTimedDialogue("This way![pause=90] It's this waaaay!!", 20)

            EXPLCOMMON.SetCharAndEmotion(kassy, "Angry")
            UI:WaitShowTimedDialogue("By the desert winds, I get it!", 90)

            EXPLCOMMON.SetCharAndEmotion(cac1, "Normal")
            UI:WaitShowDialogue("Oh, uh, sorry boss...")
            end)
      local b1 = TASK:BranchCoroutine(function()
            GROUND:Unhide("Kassy")
            GAME:FadeIn(100)
            local a2 = TASK:BranchCoroutine(function()
                  GROUND:MoveInDirection(kassy, Direction.Up, 200, false, 1)
                  end)
            local b2 = TASK:BranchCoroutine(function()
                  GROUND:MoveInDirection(cac1, Direction.Up, 200, false, 1)
                  end)
            TASK:JoinCoroutines({a2, b2})
            EXPLCOMMON.FaceEachother(kassy, cac1)
            end)
      TASK:JoinCoroutines({a1, b1})

      EXPLCOMMON.SetCharAndEmotion(kassy, "Determined")
      UI:WaitShowDialogue("...[pause=30]well?[pause=60] Where is it?!")

      EXPLCOMMON.SetCharAndEmotion(cac1, "Worried")
      UI:WaitShowTimedDialogue("U-uh,[pause=30] it's uh...[pause=90] well I could've swo")

      local a3 = TASK:BranchCoroutine(function()
            GROUND:CharSetAnim(kassy, "Attack", false)
            end)
      local b3 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(10)
            SOUND:PlaySE("Battle/DUN_Power_Gem_2")
            EXPLCOMMON.StartAndStop(cac1, "Hurt")
            end)
      TASK:JoinCoroutines({a3, b3})

      GAME:WaitFrames(80)
      EXPLCOMMON.StartAndStop(cac1, "Charge")
      EXPLCOMMON.StartTremble(cac1)

      EXPLCOMMON.SetCharAndEmotion(cac1, "Pain")
      UI:WaitShowDialogue("[speed=0.4]...b-boss...")

      EXPLCOMMON.SetCharAndEmotion(kassy, "Determined")
      UI:WaitShowDialogue("You stupid,[pause=30] petty theives are useless as grunts...!")
      UI:WaitShowDialogue("I don't know why the beast decided a bunch of absolute idiots were going to help me help him...")

      EXPLCOMMON.SetCharAndEmotion(cac1, "Pain")
      UI:WaitShowDialogue("[speed=0.4]...")

      SOUND:PlayBGM("ADarkerEvil.ogg", true)
      GAME:WaitFrames(100)
      EXPLCOMMON.SetCharAndEmotion(kassy, "Determined")
      UI:WaitShowDialogue("A bunch of little children managed to beat you here... and if that's not bad enough...")
      GROUND:CharAnimateTurnTo(kassy, Direction.UpLeft, 3)
      GAME:WaitFrames(100)

      EXPLCOMMON.SetCharAndEmotion(kassy, "Pain")
      UI:WaitShowDialogue("...you have no idea...[pause=0] no idea what you've done...!")
      GAME:WaitFrames(50)
      EXPLCOMMON.StopTremble(cac1)

      EXPLCOMMON.SetCharAndEmotion(cac1, "Pain")
      UI:WaitShowDialogue("No![pause=90][emote=Determined] N-no...!")
      GROUND:CharSetAnim(cac1, "Idle", false)
      UI:WaitShowTimedDialogue("Boss...! We'll stop them! We will stop them!!", 120)

      GROUND:MoveInDirection(cac1, Direction.Down, 200, true, 5)
      GAME:WaitFrames(50)

      GROUND:CharAnimateTurnTo(kassy, Direction.Down, 2)
      GAME:WaitFrames(50)
      GROUND:AnimateToPosition(kassy, "Walk", Dir8.Down, kassy.Position.X + 10, kassy.Position.Y + 35, 0.5, 0.2, 0)
      GAME:WaitFrames(30)
      EXPLCOMMON.SetCharAndEmotion(kassy, "Pain")
      UI:WaitShowTimedDialogue("(...[pause=50]tch.)", 90)

      EXPLCOMMON.SetCharAndEmotion(kassy, "Determined")
      UI:WaitShowDialogue("(I'll... do it myself...)")
      GAME:FadeOut(false, 240)
      GROUND:MoveInDirection(kassy, Direction.Down, 200, false, 3)

      local a4 = TASK:BranchCoroutine(function()
            GAME:FadeOut(false, 240)
            end)
      local b4 = TASK:BranchCoroutine(function()
            GROUND:MoveInDirection(kassy, Direction.Down, 200, false, 3)
            end)
      TASK:JoinCoroutines({a4, b4})

      GAME:RemovePlayerGuest(0)
      GAME:CutsceneMode(false)
      GAME:EnterGroundMap("dane_desert", "Osias", "NEnter")
end