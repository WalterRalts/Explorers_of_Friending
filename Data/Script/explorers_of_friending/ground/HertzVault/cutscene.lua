Vault = {}

function Vault.CannotOpen()
      COMMON.RespawnAllies()
      GAME:CutsceneMode(true)
      local azura = CH("Teammate1")
      local rexio = CH("Teammate2")
      local maru = CH("PLAYER")
      local coro3 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(azura, "Walk", Dir8.Up, azura.Position.X, azura.Position.Y - 20, 0.3, 0.6, 0)
            end)
      local coro4 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(rexio, "Walk", Dir8.Up, rexio.Position.X, rexio.Position.Y - 20, 0.3, 0.6, 0)
            end)
      local coro5 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(15)
            GROUND:AnimateToPosition(maru, "Walk", Dir8.Up, maru.Position.X, maru.Position.Y - 20, 0.3, 0.6, 0)
            end)
      local coro6 = TASK:BranchCoroutine(function()
            GAME:FadeIn(50)
            end)
      TASK:JoinCoroutines({coro3, coro4, coro5, coro6})

      EXPLCOMMON.SetCharAndEmotion(maru, "Normal")
      UI:WaitShowDialogue("...hm.[pause=30] Looks like a dead end.")

      EXPLCOMMON.SetCharAndEmotion(azura, "Worried")
      UI:WaitShowDialogue("What's that?")

      EXPLCOMMON.SetCharAndEmotion(maru, "Normal")
      UI:WaitShowDialogue("Oh?[pause=20] That symbol?[pause=0] Good question,[emote=Worried] no idea.")

      EXPLCOMMON.SetCharAndEmotion(rexio, "Worried")
      UI:WaitShowDialogue("Whatever,[pause=30] the treasure is probably somewhere else anyway.[pause=30][emote=Happy] Let's go.")
      GAME:CutsceneMode(false)
      EXPLCOMMON.AllyFollow(false, false)
end

function Vault.OpenUp()
      COMMON.RespawnAllies()
      GAME:CutsceneMode(true)
      local azura = CH("Teammate1")
      local rexio = CH("Teammate2")
      local maru = CH("PLAYER")
      local kassy = CH("Kassy")
      GAME:MoveCamera(180, 240, 1, false)
      local coro3 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(azura, "Walk", Dir8.Up, azura.Position.X, azura.Position.Y - 20, 0.3, 0.6, 0)
            end)
      local coro4 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(rexio, "Walk", Dir8.Up, rexio.Position.X, rexio.Position.Y - 20, 0.3, 0.6, 0)
            end)
      local coro5 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(15)
            GROUND:AnimateToPosition(maru, "Walk", Dir8.Up, maru.Position.X, maru.Position.Y - 20, 0.3, 0.6, 0)
            end)
      local coro6 = TASK:BranchCoroutine(function()
            GAME:FadeIn(50)
            EXPLCOMMON.SetCharAndEmotion(rexio, "Sigh")
            UI:WaitShowDialogue("It's our time...")
            end)
      TASK:JoinCoroutines({coro3, coro4, coro5, coro6})

      local co4 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(rexio, "Walk", Dir8.Up, OBJ("Blockade").Position.X, OBJ("Blockade").Position.Y + 30, 0.3, 0.6, 0)
            end)
      local co5 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(15)
            GROUND:AnimateToPosition(maru, "Walk", Dir8.Up, maru.Position.X, maru.Position.Y + 20, 0.3, 0.6, 0)
            end)
      TASK:JoinCoroutines({co4, co5})
      SOUND:StopBGM()

      EXPLCOMMON.SetCharAndEmotion(rexio, "Happy")
      UI:WaitShowDialogue("The treasure...[pause=80] right behind this weird looking door.")

      GROUND:CharTurnToCharAnimated(rexio, maru, 8)

      EXPLCOMMON.SetCharAndEmotion(rexio, "Inspired")
      UI:WaitShowDialogue("It was a pleasure to work with you two...")

      EXPLCOMMON.CharHappyHop("Teammate1")
      EXPLCOMMON.CharSweatdrop("PLAYER")

      EXPLCOMMON.SetCharAndEmotion(azura, "Joyous")
      UI:WaitShowDialogue("You two, Rexio!")

      EXPLCOMMON.SetCharAndEmotion(maru, "Stunned")
      UI:WaitShowDialogue("What...?")

      GROUND:CharAnimateTurnTo(rexio, Dir8.Up, 8)
      GROUND:CharSetAnim(rexio, "Attack", false)
      GAME:WaitFrames(10)
      SOUND:PlayBattleSE("DUN_Step_On_Tile")
      GAME:WaitFrames(20)
      SOUND:PlayBattleSE("EVT_CH03_Message_Board_Flip")
      GROUND:Hide("Blockade")
      GAME:WaitFrames(30)
      GROUND:Hide("Blockade_1")
      SOUND:PlayBattleSE("EVT_CH03_Message_Board_Flip")
      GAME:WaitFrames(30)
      GROUND:Hide("Blockade_2")
      SOUND:PlayBattleSE("EVT_CH03_Message_Board_Flip")
      GAME:WaitFrames(30)
      GROUND:Hide("Blockade_3")
      SOUND:PlayBattleSE("EVT_CH03_Message_Board_Flip")
      GAME:WaitFrames(30)
      GROUND:Hide("Blockade_4")
      SOUND:PlayBattleSE("EVT_CH03_Message_Board_Flip")

      local co1 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(rexio, "Walk", Dir8.Up, OBJ("Yarnball").Position.X, OBJ("Yarnball").Position.Y + 30, 0.3, 0.6, 0)
            SOUND:FadeOutBGM(120)
            end)
      local co2 = TASK:BranchCoroutine(function()
            EXPLCOMMON.SetCharAndEmotion(rexio, "Happy")
            UI:WaitShowTimedDialogue("[speed=0.75]The greatest day of the non-existent guild is near approaching.", 90)
            UI:WaitShowTimedDialogue("[speed=0.75]As I, Rexio Aurm, will collect this treasure and bring it back to safety.", 90)
            UI:WaitShowTimedDialogue("[speed=0.75]And then, we shall feast off of our cash cash gold coin cash.", 90)
            UI:WaitShowTimedDialogue("[speed=0.75]And THEN maybe they'll be able to afford to make something in the...[emote=Normal] uh...[pause=50][emote=Stunned] ...", 90)
            EXPLCOMMON.CharSweatdrop("Teammate2")
            end)
      local co3 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(40)
            GROUND:MoveToMarker(maru, MRKR("Center"), false, 2)
            GAME:WaitFrames(10)
            GROUND:CharAnimateTurnTo(maru, Dir8.Up, 8)
            end)
      TASK:JoinCoroutines({co1, co2, co3})

      GAME:WaitFrames(40)
      EXPLCOMMON.SetCharAndEmotion(maru, "Stunned")
      UI:WaitShowDialogue("Rexio?")
      local bo1 = TASK:BranchCoroutine(function()
            GAME:MoveCamera(rexio.Position.X, rexio.Position.Y, 60, false)
            GROUND:Unhide("Kassy")
            end)
      local bo2 = TASK:BranchCoroutine(function()
            GROUND:MoveToMarker(azura, MRKR("Center"), false, 2)
            GROUND:MoveToMarker(azura, MRKR("CenterUp"), false, 2)
            GROUND:MoveToMarker(azura, MRKR("Left"), false, 2)
            GROUND:CharAnimateTurnTo(azura, Dir8.UpRight, 8)
            end)
      local bo3 = TASK:BranchCoroutine(function()
            GROUND:MoveToMarker(maru, MRKR("CenterUp"), false, 2)
            GROUND:MoveToMarker(maru, MRKR("Right"), false, 2)
            GROUND:CharAnimateTurnTo(maru, Dir8.UpLeft, 8)
            end)
      TASK:JoinCoroutines({bo1, bo2, bo3})

      
      EXPLCOMMON.SetCharAndEmotion(maru, "Normal")
      UI:WaitShowDialogue("Oh, cool. It's a yarn ball, I think.")

      EXPLCOMMON.SetCharAndEmotion(azura, "Worried")
      UI:WaitShowDialogue("You think it belongs to Ms. Kitkat?")
      EXPLCOMMON.FaceEachother(maru, azura)

      EXPLCOMMON.SetCharAndEmotion(rexio, "Worried")
      UI:WaitShowDialogue("Mm...[pause=30] well, I guess,[pause=60][emote=Stunned] and I hope,[pause=45] it's a valuable ball of yarn.")
      
      EXPLCOMMON.SetCharAndEmotion(maru, "Normal")
      UI:WaitShowDialogue("It's on a pedestal.[pause=60][emote=Happy] You worry too much.")

      GROUND:CharAnimateTurnTo(azura, Dir8.UpLeft, 8)
      EXPLCOMMON.SetCharAndEmotion(azura, "Inspired")
      UI:WaitShowDialogue("With all this gold around it...!")

      EXPLCOMMON.SetCharAndEmotion(rexio, "Sigh")
      UI:WaitShowDialogue("You'd better be right, Bluetail.")
      function next()
            local bh2 = TASK:BranchCoroutine(function()
                  GROUND:MoveToPosition(rexio, rexio.Position.X, rexio.Position.Y + 80, false, 1)
                  end)
            local bh3 = TASK:BranchCoroutine(function()
                  GROUND:MoveObjectToPosition(OBJ("Yarnball"), rexio.Position.X, rexio.Position.Y + 80, 1)
                  end)
            TASK:JoinCoroutines({bh2, bh3})
      end
      TASK:StartEntityTask(rexio, next)
      GROUND:MoveToPosition(kassy, rexio.Position.X, rexio.Position.Y + 80, false, 5)
      TASK:StopEntityTask(rexio)
      GROUND:CharSetAnim(kassy, "Attack", false)
      local bha2 = TASK:BranchCoroutine(function()
            EXPLCOMMON.CharExclaim("PLAYER")
            EXPLCOMMON.CharRealizeHeavy("Teammate1")
            GROUND:AnimateToPosition(rexio, "Laying", Dir8.Left, rexio.Position.X, rexio.Position.Y - 50, 1, 2, 0)
            GROUND:CharSetAction(rexio, RogueEssence.Ground.PoseGroundAction(rexio.Position, rexio.Direction, RogueEssence.Content.GraphicsManager.GetAnimIndex("Laying")))

            EXPLCOMMON.SetCharAndEmotion(maru, "Surprised")
            UI:WaitShowDialogue("Rexio!")

            EXPLCOMMON.SetCharAndEmotion(azura, "Surprised")
            UI:WaitShowDialogue("Oh no!!")

            EXPLCOMMON.StartTremble(rexio)
            GAME:WaitFrames(25)
            EXPLCOMMON.StopTremble(rexio)
            GAME:WaitFrames(25)
            GROUND:CharSetAnim(rexio, "Wake", false)

            EXPLCOMMON.SetCharAndEmotion(rexio, "Angry")
            UI:WaitShowTimedDialogue("OH, NO WAY![pause=90] NO WAAAAAAY!", 90)
            end)
      local bha3 = TASK:BranchCoroutine(function()
            GROUND:MoveObjectToPosition(OBJ("Yarnball"), kassy.Position.X, kassy.Position.Y, 1)
            local bh2 = TASK:BranchCoroutine(function()
                  GROUND:MoveObjectToPosition(OBJ("Yarnball"), kassy.Position.X, kassy.Position.Y + 100, 6)
                  end)
            local bh3 = TASK:BranchCoroutine(function()
                  GROUND:MoveToPosition(kassy, kassy.Position.X, kassy.Position.Y + 100, true, 6)
                  GROUND:Hide("Kassy")
                  SOUND:PlayBattleSE("DUN_Send_Home")
                  end)
            TASK:JoinCoroutines({bh2, bh3})
            end)
      TASK:JoinCoroutines({bha2, bha3})
      EXPLCOMMON.SetCharAndEmotion(azura, "Sad")
      UI:WaitShowDialogue("Aww, the treasure...")

      EXPLCOMMON.SetCharAndEmotion(rexio, "Angry")
      UI:WaitShowDialogue("NO \"AWWWW\"! LET'S GET THEM!!")

      local coro13 = TASK:BranchCoroutine(function()
            GROUND:MoveToMarker(azura, MRKR("CenterUp"), true, 5)
            GROUND:AnimateToPosition(azura, "Run", Dir8.Down, azura.Position.X, azura.Position.Y + 200, 2, 5, 0)
            end)
      local coro14 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(rexio, "Run", Dir8.Down, rexio.Position.X, rexio.Position.Y + 200, 2, 5, 0)
            end)
      local coro15 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(15)
            GROUND:MoveToMarker(maru, MRKR("CenterUp"), true, 5)
            GROUND:AnimateToPosition(maru, "Run", Dir8.Down, maru.Position.X, maru.Position.Y + 200, 2, 5, 0)
            end)
      local coro16 = TASK:BranchCoroutine(function()
            GAME:FadeOut(false, 50)
            end)
      TASK:JoinCoroutines({coro13, coro14, coro15, coro16})

      GAME:CutsceneMode(false)
      GAME:EnterGroundMap("HertzEntrance", "EnterN", false)
end