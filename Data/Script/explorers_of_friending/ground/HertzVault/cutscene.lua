Vault = {}

function Vault.CannotOpen()
      COMMON.RespawnAllies()
      GAME:CutsceneMode(true)
      local azura = CH("Teammate1")
      local rexio = CH("Teammate2")
      local maru = CH("PLAYER")
      local coro3 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(azura, "Walk", Dir8.Up, azura.Position.X, azura.Position.Y - 20, 0.3, 0.6, 0)
            end)
      local coro4 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(rexio, "Walk", Dir8.Up, rexio.Position.X, rexio.Position.Y - 20, 0.3, 0.6, 0)
            end)
      local coro5 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(15)
            GROUND:AnimateToPosition(maru, "Walk", Dir8.Up, maru.Position.X, maru.Position.Y - 20, 0.3, 0.6, 0)
            end)
      local coro6 = TASK:BranchCoroutine(function()
            GAME:FadeIn(50)
            end)
      TASK:JoinCoroutines({coro3, coro4, coro5, coro6})

      EXPLCOMMON.SetCharAndEmotion(maru, "Normal")
      UI:WaitShowDialogue("...hm.[pause=30] Looks like a dead end.")

      EXPLCOMMON.SetCharAndEmotion(azura, "Worried")
      UI:WaitShowDialogue("What's that?")

      EXPLCOMMON.SetCharAndEmotion(maru, "Normal")
      UI:WaitShowDialogue("Oh?[pause=20] That symbol?[pause=0] Good question,[emote=Worried] no idea.")

      EXPLCOMMON.SetCharAndEmotion(rexio, "Worried")
      UI:WaitShowDialogue("Whatever,[pause=30] the treasure is probably somewhere else anyway.[pause=30][emote=Happy] Let's go.")
      GAME:CutsceneMode(false)
      EXPLCOMMON.AllyFollow(false, false)
end

function Vault.OpenUp()
      COMMON.RespawnAllies()
      GAME:CutsceneMode(true)
      local azura = CH("Teammate1")
      local rexio = CH("Teammate2")
      local maru = CH("PLAYER")
      GAME:MoveCamera(180, 240, 1, false)
      local coro3 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(azura, "Walk", Dir8.Up, azura.Position.X, azura.Position.Y - 20, 0.3, 0.6, 0)
            end)
      local coro4 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(rexio, "Walk", Dir8.Up, rexio.Position.X, rexio.Position.Y - 20, 0.3, 0.6, 0)
            end)
      local coro5 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(15)
            GROUND:AnimateToPosition(maru, "Walk", Dir8.Up, maru.Position.X, maru.Position.Y - 20, 0.3, 0.6, 0)
            end)
      local coro6 = TASK:BranchCoroutine(function()
            GAME:FadeIn(50)

            EXPLCOMMON.SetCharAndEmotion(rexio, "Sigh")
            UI:WaitShowDialogue("It's our time...")
            end)
      TASK:JoinCoroutines({coro3, coro4, coro5, coro6})

      local co4 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(rexio, "Walk", Dir8.Up, OBJ("Blockade").Position.X, OBJ("Blockade").Position.Y + 30, 0.3, 0.6, 0)
            end)
      local co5 = TASK:BranchCoroutine(function()
            GAME:WaitFrames(15)
            GROUND:AnimateToPosition(maru, "Walk", Dir8.Up, maru.Position.X, maru.Position.Y + 20, 0.3, 0.6, 0)
            end)
      TASK:JoinCoroutines({co4, co5})

      EXPLCOMMON.SetCharAndEmotion(rexio, "Happy")
      UI:WaitShowDialogue("The treasure...[pause=80] right behind this weird looking door.")

      GROUND:CharTurnToCharAnimated(rexio, maru, 8)

      EXPLCOMMON.SetCharAndEmotion(rexio, "Inspired")
      UI:WaitShowDialogue("It was a pleasure to work with you two...")

      EXPLCOMMON.CharHappyHop("Teammate1")
      EXPLCOMMON.CharSweatdrop("PLAYER")

      EXPLCOMMON.SetCharAndEmotion(azura, "Joyous")
      UI:WaitShowDialogue("You two, Rexio!")

      EXPLCOMMON.SetCharAndEmotion(maru, "Stunned")
      UI:WaitShowDialogue("What...?")

      GROUND:CharAnimateTurnTo(rexio, Dir8.Up, 8)
      GROUND:CharSetAnim(rexio, "Attack", false)
      GAME:WaitFrames(10)
      SOUND:PlayBattleSE("DUN_Step_On_Tile")
      GAME:WaitFrames(20)
      SOUND:PlayBattleSE("EVT_CH03_Message_Board_Flip")
      GROUND:Hide("Blockade")
      GAME:WaitFrames(30)
      GROUND:Hide("Blockade_1")
      SOUND:PlayBattleSE("EVT_CH03_Message_Board_Flip")
      GAME:WaitFrames(30)
      GROUND:Hide("Blockade_2")
      SOUND:PlayBattleSE("EVT_CH03_Message_Board_Flip")
      GAME:WaitFrames(30)
      GROUND:Hide("Blockade_3")
      SOUND:PlayBattleSE("EVT_CH03_Message_Board_Flip")
      GAME:WaitFrames(30)
      GROUND:Hide("Blockade_4")
      SOUND:PlayBattleSE("EVT_CH03_Message_Board_Flip")

      local co1 = TASK:BranchCoroutine(function()
            GROUND:AnimateToPosition(rexio, "Walk", Dir8.Up, OBJ("Yarnball").Position.X, OBJ("Yarnball").Position.Y + 30, 0.3, 0.6, 0)
            end)
      local co2 = TASK:BranchCoroutine(function()
            EXPLCOMMON.SetCharAndEmotion(rexio, "Happy")
            UI:WaitShowTimedDialogue("[speed=0.75]The greatest day of the non-existent guild is near approaching.", 90)
            UI:WaitShowTimedDialogue("[speed=0.75]As I, Rexio Aurm, will collect this treasure and bring it back to safety.", 90)
            UI:WaitShowTimedDialogue("[speed=0.75]And then, we shall feast off of our cash cash gold coin cash.", 90)
            UI:WaitShowTimedDialogue("[speed=0.75]And THEN maybe they'll be able to afford to make something in the...[emote=Normal] uh...[pause=50][emote=Stunned] ...", 90)
            end)
      TASK:JoinCoroutines({co1, co2})

      GAME:CutsceneMode(false)
      EXPLCOMMON.AllyFollow(false, false)
end